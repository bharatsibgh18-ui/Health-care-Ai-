    fun translate(languageId: String, englishText: String): String? {
        val exact = phraseTable[englishText]?.get(languageId)
        if (exact != null) return exact

        val trimmed = englishText.trim()
        val normalized = normalizedIndex[trimmed.lowercase()]?.get(languageId)
        if (normalized != null) return normalized

        // Dynamic pattern translations for parameterized labels
        if (trimmed.startsWith("Users (") && trimmed.endsWith(")")) {
            val countPart = trimmed.substringAfter("Users ")
            usersWord[languageId]?.let { return "$it $countPart" }
        }
        if (trimmed.startsWith("Theme: ")) {
            val themeVal = trimmed.removePrefix("Theme: ")
            themeWord[languageId]?.let { return "$it: $themeVal" }
        }
        return null
    }
